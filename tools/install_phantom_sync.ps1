try {
  foreach($folder in @($ProjectRoot,$PreviewDir,$SourcesDir)) {
    if(-not(Test-Path -LiteralPath $folder -PathType Container)) { throw "Не найдена папка проекта: $folder" }
  }
  $Python=Get-Command python -ErrorAction SilentlyContinue
  if(-not $Python) { throw 'Python не найден. Эта версия обновлятора требует рабочую команду python (как при запуске предыдущих скриптов).' }
  if(-not(Get-Command ssh -ErrorAction SilentlyContinue)) {throw 'Не найден OpenSSH: ssh.exe'}
  if(-not(Get-Command scp -ErrorAction SilentlyContinue)) {throw 'Не найден OpenSSH: scp.exe'}
  $bytes=[Convert]::FromBase64String(($Compressed -replace '\s',''))
  $stream=[IO.MemoryStream]::new($bytes)
  $gzip=[IO.Compression.GzipStream]::new($stream,[IO.Compression.CompressionMode]::Decompress)
  $out=[IO.MemoryStream]::new()
  try {$gzip.CopyTo($out)} finally {$gzip.Dispose();$stream.Dispose()}
  $payload=$out.ToArray();$out.Dispose()
  $sha=[Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($payload)).ToLowerInvariant()
  if($sha -ne $ExpectedHash){throw 'Контрольная сумма установочного пакета не совпала. Установка отменена.'}
  [IO.Directory]::CreateDirectory($ToolDir)|Out-Null
  if(Test-Path -LiteralPath $ToolPath -PathType Leaf){
    Copy-Item -LiteralPath $ToolPath -Destination ($ToolPath+'.before-install-'+(Get-Date -Format 'yyyyMMdd-HHmmss')+'.bak') -Force
  }
  [IO.File]::WriteAllBytes($ToolPath,$payload)
  $cmd = @'
@echo off
chcp 65001 >nul
set "PYTHONUTF8=1"
set "PROJECT=__ROOT__"
set "UPDATER=__ROOT__\tools\phantom_sync.py"
cd /d "%PROJECT%"
python -I "%UPDATER%" --root "%PROJECT%" --accept-initial --open
set "RESULT=%ERRORLEVEL%"
echo.
if "%RESULT%"=="0" (echo PHANTOM SYNC: DONE) else (echo PHANTOM SYNC: ERROR %RESULT% - see details above)
echo.
pause
exit /b %RESULT%
'@
  $cmd=$cmd.Replace('__ROOT__',$ProjectRoot)
  $cmd=$cmd.Replace("`r`n","`n").Replace("`n","`r`n")
  [IO.File]::WriteAllText($CmdPath,$cmd,[Text.UTF8Encoding]::new($false))
  $desktop=[Environment]::GetFolderPath('Desktop')
  if(-not $desktop){throw 'Не найдена папка рабочего стола. Файл запуска создан в корне проекта.'}
  $ShortcutPath=Join-Path $desktop 'Обновить Phantom.lnk'
  $shell=New-Object -ComObject WScript.Shell
  $shortcut=$shell.CreateShortcut($ShortcutPath)
  $shortcut.TargetPath=$CmdPath
  $shortcut.WorkingDirectory=$ProjectRoot
  $shortcut.Description='GitHub -> локальный проект -> тестовый AEZA; резервные копии и проверка SHA-256'
  $shortcut.WindowStyle=1
  $shortcut.IconLocation=($env:SystemRoot+'\System32\shell32.dll,167')
  $shortcut.Save()
  Write-Host ('INSTALLED: ' + $ToolPath) -ForegroundColor Green
  Write-Host ('BUTTON: ' + $ShortcutPath) -ForegroundColor Green
  Write-Host 'Первый запуск может перезаписать старые локальные копии данными GitHub, сохранив backup. Последующие локальные конфликты блокируются.' -ForegroundColor Yellow
